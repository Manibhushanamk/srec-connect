import { NextRequest, NextResponse } from 'next/server';
import { getServerSession } from 'next-auth';
import { authOptions } from '@/lib/auth';
import prisma from '@/lib/prisma';

/**
 * Access check helper: Only SUPER_ADMIN, ADMIN, and HOD can access institutional audit logs
 */
async function getAuthorizedAuditUser() {
  const session = await getServerSession(authOptions);
  if (!session?.user?.email) return null;

  const user = await prisma.user.findUnique({
    where: { email: session.user.email.toLowerCase().trim() },
    select: {
      id: true,
      name: true,
      email: true,
      role: true,
      status: true,
      departmentId: true,
      department: { select: { id: true, name: true, code: true } },
      faculty: { select: { id: true, departmentId: true, departmentName: true } },
    },
  });

  if (
    !user ||
    user.status !== 'ACTIVE' ||
    (user.role !== 'SUPER_ADMIN' && user.role !== 'ADMIN' && user.role !== 'HOD')
  ) {
    return null;
  }
  return user;
}

export async function GET(req: NextRequest) {
  try {
    const user = await getAuthorizedAuditUser();
    if (!user) {
      return NextResponse.json(
        { error: 'Forbidden: Audit log access is strictly restricted to HOD and Super Admin' },
        { status: 403 }
      );
    }

    const { searchParams } = new URL(req.url);
    const search = searchParams.get('search')?.trim() || '';
    const actionFilter = searchParams.get('action') || 'ALL';
    const entityTypeFilter = searchParams.get('entityType') || 'ALL';
    const roleFilter = searchParams.get('role') || 'ALL';
    const dateRange = searchParams.get('dateRange') || 'all';
    const exportFormat = searchParams.get('export');
    const page = Math.max(1, parseInt(searchParams.get('page') || '1', 10));
    const limit = Math.min(100, Math.max(10, parseInt(searchParams.get('limit') || '50', 10)));
    const skip = (page - 1) * limit;

    // Base WHERE clause
    const where: any = {};

    // 1. Department Scope: If HOD, scope to actors or entities within HOD's department
    if (user.role === 'HOD') {
      const hodDeptId = user.departmentId || user.faculty?.departmentId;
      if (hodDeptId) {
        // HOD sees logs generated by members of their department or actions performed on their department
        const deptUsers = await prisma.user.findMany({
          where: { departmentId: hodDeptId },
          select: { id: true },
        });
        const deptUserIds = deptUsers.map((u) => u.id);
        deptUserIds.push(user.id);

        where.OR = [
          { actorId: { in: deptUserIds } },
          { metadata: { contains: hodDeptId } },
          ...(user.department?.code ? [{ metadata: { contains: user.department.code } }] : []),
          ...(user.department?.name ? [{ metadata: { contains: user.department.name } }] : []),
        ];
      }
    }

    // 2. Action Filter
    if (actionFilter && actionFilter !== 'ALL') {
      if (actionFilter === 'MODERATION') {
        where.action = { in: ['ACHIEVEMENT_PUBLISHED', 'ACHIEVEMENT_PUBLISH', 'ACHIEVEMENT_APPROVED', 'ACHIEVEMENT_REJECTED', 'INCIDENT_RESOLVED'] };
      } else if (actionFilter === 'SECURITY') {
        where.action = { in: ['USER_UPDATED', 'ROLE_CHANGED', 'USER_SUSPENDED', 'PASSWORD_RESET', 'LOGIN_SUCCESS', 'LOGIN_FAILED'] };
      } else if (actionFilter === 'DATA') {
        where.action = { in: ['DRIVE_FILE_UPLOADED', 'BULK_IMPORT', 'EXPORT_GENERATED', 'STUDENT_CREATED'] };
      } else if (actionFilter === 'TRASH') {
        where.action = { in: ['TRASH_RESTORE', 'TRASH_PURGE', 'TRASH_EMPTY'] };
      } else {
        where.action = { contains: actionFilter, mode: 'insensitive' };
      }
    }

    // 3. Entity Type Filter
    if (entityTypeFilter && entityTypeFilter !== 'ALL') {
      where.entityType = { equals: entityTypeFilter, mode: 'insensitive' };
    }

    // 4. Role Filter
    if (roleFilter && roleFilter !== 'ALL') {
      where.actorRole = roleFilter;
    }

    // 5. Date Range Filter
    if (dateRange !== 'all') {
      const now = new Date();
      if (dateRange === 'today') {
        const startOfDay = new Date(now.getFullYear(), now.getMonth(), now.getDate());
        where.createdAt = { gte: startOfDay };
      } else if (dateRange === '7d') {
        const sevenDaysAgo = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000);
        where.createdAt = { gte: sevenDaysAgo };
      } else if (dateRange === '30d') {
        const thirtyDaysAgo = new Date(now.getTime() - 30 * 24 * 60 * 60 * 1000);
        where.createdAt = { gte: thirtyDaysAgo };
      }
    }

    // 6. Search Query Filter
    if (search) {
      const searchConditions = [
        { actorEmail: { contains: search, mode: 'insensitive' } },
        { action: { contains: search, mode: 'insensitive' } },
        { entityType: { contains: search, mode: 'insensitive' } },
        { entityId: { contains: search, mode: 'insensitive' } },
        { metadata: { contains: search, mode: 'insensitive' } },
        { ipAddress: { contains: search, mode: 'insensitive' } },
      ];

      if (where.OR) {
        where.AND = [
          { OR: where.OR },
          { OR: searchConditions },
        ];
        delete where.OR;
      } else {
        where.OR = searchConditions;
      }
    }

    // Handle CSV/JSON Export
    if (exportFormat === 'csv' || exportFormat === 'json') {
      const exportLogs = await prisma.auditLog.findMany({
        where,
        orderBy: { createdAt: 'desc' },
        take: 1000,
        include: {
          actor: {
            select: {
              id: true,
              name: true,
              email: true,
              role: true,
            },
          },
        },
      });

      if (exportFormat === 'json') {
        return new NextResponse(JSON.stringify(exportLogs, null, 2), {
          headers: {
            'Content-Type': 'application/json',
            'Content-Disposition': `attachment; filename="srec-audit-logs-${new Date().toISOString().slice(0, 10)}.json"`,
          },
        });
      }

      // Format CSV
      const csvRows = [
        ['Timestamp (UTC)', 'Log ID', 'Actor Name', 'Actor Email', 'Actor Role', 'Action', 'Entity Type', 'Entity ID', 'IP Address', 'Metadata'].join(','),
        ...exportLogs.map((log) => {
          const escapeCsv = (str?: string | null) => `"${(str || '').replace(/"/g, '""')}"`;
          return [
            escapeCsv(log.createdAt.toISOString()),
            escapeCsv(log.id),
            escapeCsv(log.actor?.name || 'System'),
            escapeCsv(log.actorEmail),
            escapeCsv(log.actorRole),
            escapeCsv(log.action),
            escapeCsv(log.entityType),
            escapeCsv(log.entityId),
            escapeCsv(log.ipAddress || 'Internal'),
            escapeCsv(log.metadata || '{}'),
          ].join(',');
        }),
      ];

      return new NextResponse(csvRows.join('\n'), {
        headers: {
          'Content-Type': 'text/csv; charset=utf-8',
          'Content-Disposition': `attachment; filename="srec-audit-logs-${new Date().toISOString().slice(0, 10)}.csv"`,
        },
      });
    }

    // Query Total & Paginated Results
    const [total, logs] = await Promise.all([
      prisma.auditLog.count({ where }),
      prisma.auditLog.findMany({
        where,
        orderBy: { createdAt: 'desc' },
        skip,
        take: limit,
        include: {
          actor: {
            select: {
              id: true,
              name: true,
              email: true,
              role: true,
              avatarUrl: true,
              department: { select: { name: true, code: true } },
            },
          },
        },
      }),
    ]);

    // Aggregate Summary KPI Statistics
    const now = new Date();
    const startOfToday = new Date(now.getFullYear(), now.getMonth(), now.getDate());

    const [todayCount, moderationCount, securityCount, topActionsRaw] = await Promise.all([
      prisma.auditLog.count({
        where: {
          ...(user.role === 'HOD' && where.OR ? { OR: where.OR } : {}),
          createdAt: { gte: startOfToday },
        },
      }),
      prisma.auditLog.count({
        where: {
          ...(user.role === 'HOD' && where.OR ? { OR: where.OR } : {}),
          action: { in: ['ACHIEVEMENT_PUBLISHED', 'ACHIEVEMENT_PUBLISH', 'ACHIEVEMENT_APPROVED', 'ACHIEVEMENT_REJECTED'] },
        },
      }),
      prisma.auditLog.count({
        where: {
          ...(user.role === 'HOD' && where.OR ? { OR: where.OR } : {}),
          action: { in: ['USER_UPDATED', 'ROLE_CHANGED', 'USER_SUSPENDED', 'PASSWORD_RESET', 'TRASH_PURGE'] },
        },
      }),
      prisma.auditLog.groupBy({
        by: ['action'],
        where: user.role === 'HOD' && where.OR ? { OR: where.OR } : {},
        _count: { action: true },
        orderBy: { _count: { action: 'desc' } },
        take: 6,
      }),
    ]);

    const stats = {
      totalEvents: total,
      todayEvents: todayCount,
      moderationEvents: moderationCount,
      securityEvents: securityCount,
      topActions: topActionsRaw.map((a) => ({ action: a.action, count: a._count.action })),
      currentUserRole: user.role,
      departmentName: user.department?.name || 'Institution-wide',
    };

    return NextResponse.json({
      success: true,
      logs,
      total,
      page,
      totalPages: Math.ceil(total / limit) || 1,
      stats,
    });
  } catch (error: any) {
    console.error('[API Admin Logs GET] Error:', error);
    return NextResponse.json({ error: error.message || 'Failed to retrieve audit logs' }, { status: 500 });
  }
}
